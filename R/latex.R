#' Format numbers for LaTeX with a typographic minus.
#' With keep_sign, -0.003 prints as "-0.00", so a bold interval never appears to touch zero from the wrong side.
tex_num <- function(x, d, keep_sign = FALSE) {
  r <- round(x, d)
  s <- sub("^-", "", formatC(r, format = "f", digits = d))
  neg <- !is.na(x) & (if (keep_sign) x < 0 else r < 0)
  s[neg] <- paste0("\\textminus{}", s[neg])
  s[is.na(x)] <- "---"
  s
}

#' "median (lo, hi)", optionally bold.
tex_cri <- function(med, lo, hi, d = 2, bold = FALSE) {
  s <- sprintf("%s (%s, %s)", tex_num(med, d), tex_num(lo, d, TRUE), tex_num(hi, d, TRUE))
  if (bold) s <- sprintf("\\textbf{%s}", s)
  s
}

excludes_zero <- function(lo, hi) !is.na(lo) & (lo > 0 | hi < 0)

tex_header <- function() "% generated by scripts/04_figures_tables.R -- edit the script, not this file"

# "\\*" forbids a page break straight after a heading row
tex_panel_head <- function(txt, nc) sprintf("\\multicolumn{%d}{@{}l}{\\textbf{%s}}\\\\*", nc, txt)
tex_group_head <- function(txt, nc) sprintf("\\multicolumn{%d}{@{}l}{\\quad\\emph{%s}}\\\\*", nc, txt)
tex_row <- function(label, cells) sprintf("\\qquad %s & %s \\\\", label, paste(cells, collapse = " & "))

#' A longtable with repeated headers, a caption and a notes paragraph.
tex_longtable <- function(ncol_num, colhead, caption, label, body, notes) {
  nc <- 1 + ncol_num
  c(
    tex_header(),
    "{\\footnotesize",
    sprintf("\\setlength{\\tabcolsep}{%dpt}", if (ncol_num >= 3) 3L else 5L),
    "\\setlength{\\LTcapwidth}{\\linewidth}",
    "\\renewcommand{\\arraystretch}{0.93}",
    sprintf("\\begin{longtable}{%s}", paste0("@{}l", strrep("c", ncol_num), "@{}")),
    sprintf("\\caption{%s}\\label{%s}\\\\", caption, label),
    "\\toprule", colhead, "\\midrule", "\\endfirsthead",
    sprintf("\\multicolumn{%d}{@{}l}{\\emph{Table \\thetable, continued}}\\\\", nc),
    "\\toprule", colhead, "\\midrule", "\\endhead",
    "\\midrule",
    sprintf("\\multicolumn{%d}{r@{}}{\\emph{continued on next page}}\\\\", nc),
    "\\endfoot",
    "\\bottomrule",
    "\\endlastfoot",
    body,
    "\\end{longtable}",
    "\\vspace{-0.6\\baselineskip}",
    sprintf("{\\scriptsize\\noindent %s\\par}", notes), "}"
  )
}
